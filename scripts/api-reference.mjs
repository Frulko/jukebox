// Writes a Markdown API reference from the OpenAPI document.
//
// A hand-kept route list is exactly the thing this project already decided not
// to trust: `docs/api.md` drifted to describing 42 of 102 routes without anyone
// noticing, which is how a document becomes actively misleading rather than
// merely incomplete.
//
// So the reference is generated. The prose lives in `openapi.ts` beside the
// routes it describes, a test fails when a route has none, and this turns the
// result into something a docs site can include.
//
//   node scripts/api-reference.mjs              → stdout
//   node scripts/api-reference.mjs docs/foo.md  → written there
//
// Deliberately takes its destination as an argument rather than choosing one:
// where the documentation lives is the docs site's business, not this script's.

import { writeFileSync } from 'node:fs'
import { createApp } from '../apps/server/src/app.ts'
import { buildOpenApi } from '../apps/server/src/openapi.ts'

const { app, jobs } = createApp(':memory:')
const spec = buildOpenApi(app)
jobs.stop()

/** Groups operations by their tag, keeping the order they were declared in. */
const byTag = new Map()
for (const [path, operations] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(operations)) {
    const tag = op.tags?.[0] ?? 'other'
    byTag.set(tag, [...(byTag.get(tag) ?? []), { path, method: method.toUpperCase(), op }])
  }
}

const lines = [
  '<!-- Generated by scripts/api-reference.mjs. Edits here are lost; the prose',
  '     lives in apps/server/src/openapi.ts, beside the routes it describes. -->',
  '',
  '# API reference',
  '',
  spec.info.description,
  '',
  `Base URL: \`${spec.servers[0].url}\``,
  '',
  'Authentication is a bearer token, or `?token=` for the places that cannot set',
  'a header — `<audio src>` being the reason that exists. A server with no',
  'accounts answers everything, so a fresh install is usable before anyone has',
  'created a login.',
  '',
]

for (const [tag, operations] of [...byTag.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`## ${tag}`, '')
  lines.push('| | Path | What it does |', '|---|---|---|')

  for (const { path, method, op } of operations.sort((a, b) => a.path.localeCompare(b.path))) {
    // The pipe is the table's own delimiter; a summary containing one would
    // silently split the row into extra columns.
    const summary = op.summary.replace(/\|/g, '\\|')
    lines.push(`| \`${method}\` | \`${path}\` | ${summary} |`)
  }
  lines.push('')

  // Bodies and query parameters, only where there are any, so the table above
  // stays scannable and the detail is one glance further down.
  const detailed = operations.filter((o) => o.op.requestBody || o.op.parameters?.some((p) => p.in === 'query'))
  if (detailed.length) {
    for (const { path, method, op } of detailed) {
      const query = (op.parameters ?? []).filter((p) => p.in === 'query').map((p) => `\`${p.name}\``)
      const body = op.requestBody?.content?.['application/json']?.example
      lines.push(`**\`${method} ${path}\`**  `)
      if (body) lines.push(`Body: \`${body}\`  `)
      if (query.length) lines.push(`Query: ${query.join(', ')}  `)
      lines.push('')
    }
  }
}

lines.push(
  '## Not described here',
  '',
  'A Subsonic-compatible API is served at `/rest`. It is somebody else\'s',
  'specification and they document it; every client written for it in the last',
  'twenty years works against this server unchanged.',
  '',
)

const out = lines.join('\n')
const target = process.argv[2]
if (target) {
  writeFileSync(target, out)
  console.error(`api reference · ${Object.keys(spec.paths).length} paths → ${target}`)
} else {
  process.stdout.write(out)
}
